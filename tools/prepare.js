function cityFromAddr(a) {
  if (!a) return null;
  for (const [county, city] of COUNTY_CITY) if (a.includes(county)) return city;
  for (const c of CITIES) if (a.includes(c)) return c;
  return null;
}

function districtFromAddr(a, city) {
  if (!a) return '';
  let s = a.replace(/^广东省/, '').replace(/^中国/, '');
  if (city) s = s.replace(city, '').replace(/^市/, '');

  // 1) 直接带行政区划后缀。区/县先行，避免「番禺区市桥」被截成「番禺区市」
  const m = s.match(/^([\u4e00-\u9fa5]{1,3}区)/)
    || s.match(/^([\u4e00-\u9fa5]{1,3}县)/)
    || s.match(/^([\u4e00-\u9fa5]{1,3}市)(?![\u4e00-\u9fa5]{2}(?:路|街|道|镇|村|区))/)
    || s.match(/^([\u4e00-\u9fa5]{1,3}(?:镇|街道|新区|开发区|办事处))/);
  if (m && m[1] !== '市') return m[1];

  // 2) 片区关键词（长词优先）
  const full = a;
  let best = null;
  for (const [kw, kcity, kdist] of AREA) {
    if (kcity !== city) continue;
    if (!full.includes(kw)) continue;
    if (!best || kw.length > best[0].length) best = [kw, kdist];
  }
  if (best) return best[1];

  return '';
}

